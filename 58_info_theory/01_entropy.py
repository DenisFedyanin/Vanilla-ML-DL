"""Раздел 58 — Теория информации.

Файл 1: Энтропия и взаимная информация.

Концепция: Энтропия Шеннона.
H(X) = -sum p(x) log p(x). Среднее количество бит/натов на сэмпл из X.
Равна 0 для детерминированной СВ и максимальна (log k) на равномерном распределении.

Концепция: Совместная энтропия.
H(X,Y) = -sum p(x,y) log p(x,y). Энтропия пары случайных величин.
H(X,Y) <= H(X)+H(Y) с равенством при независимости.

Концепция: Условная энтропия.
H(Y|X) = H(X,Y) - H(X). Сколько "осталось неопределенности" о Y, зная X.
Также: H(Y|X) = sum_x p(x) H(Y|X=x). Всегда <= H(Y).

Концепция: Взаимная информация (MI).
I(X;Y) = H(X) + H(Y) - H(X,Y) = sum p(x,y) log(p(x,y)/(p(x)p(y))).
Сколько информации о Y дает X. I=0 <=> X и Y независимы.
"""
import numpy as np

# Совместное распределение p(x,y), x in {0,1,2}, y in {0,1}
p_xy = np.array([[0.10, 0.20],
                 [0.30, 0.05],
                 [0.05, 0.30]])
assert abs(p_xy.sum() - 1.0) < 1e-9

p_x = p_xy.sum(axis=1)
p_y = p_xy.sum(axis=0)

def H(p):
    p = p[p > 0]
    return -np.sum(p * np.log2(p))

H_X = H(p_x)
H_Y = H(p_y)
H_XY = H(p_xy.ravel())
H_Y_given_X = H_XY - H_X
I_XY = H_X + H_Y - H_XY

print(f"H(X)={H_X:.4f}, H(Y)={H_Y:.4f}, H(X,Y)={H_XY:.4f}")
print(f"H(Y|X)={H_Y_given_X:.4f}, H(X|Y)={H_XY - H_Y:.4f}")
print(f"I(X;Y)={I_XY:.4f} (бит)")

# Проверка: для независимых X,Y MI=0
p_indep = np.outer(p_x, p_y)
H_indep = H(p_indep.ravel())
print(f"Независимый случай: I(X;Y) = {H_X + H_Y - H_indep:.6f} (~0)")

# Нормированная MI
NMI = 2 * I_XY / (H_X + H_Y)
print(f"Нормированная MI = {NMI:.4f} (1=полная зависимость)")

# Максимальная энтропия достигается на равномерном
print(f"H(Uniform_4) = {H(np.full(4, 1/4)):.4f} = log2(4)=2")
