"""Раздел 61 — Вероятность (расширение).

Файл 1: Базовые понятия.

Концепция: Пространство элементарных исходов.
Omega — множество всех возможных результатов случайного эксперимента.
Событие A — подмножество Omega. P(A) — вероятность события.

Концепция: Сигма-алгебра (интуиция).
Семейство подмножеств Omega, замкнутое относительно дополнения и счетных объединений.
Нужна чтобы P(A) была корректно определена для интересующих нас событий.

Концепция: Независимость.
A и B независимы, если P(A and B) = P(A) P(B). Симметрично.
Не путать с несовместностью (когда A and B = пусто, что для P>0 НЕ влечет независимость).

Концепция: Условная вероятность.
P(A | B) = P(A and B) / P(B), P(B)>0. Перенормировка на "случилось B".

Концепция: Формула полной вероятности.
Если B_1..B_n — разбиение Omega: P(A) = sum_i P(A | B_i) P(B_i).

Концепция: Теорема Байеса.
P(A|B) = P(B|A) P(A) / P(B). Связь априори и апостериори.
"""
import numpy as np

rng = np.random.default_rng(0)

# === Моделируем 2 монеты, считаем P событий эмпирически ===
N = 100_000
c1 = rng.integers(0, 2, N)
c2 = rng.integers(0, 2, N)

P_A = (c1 == 1).mean()  # первая орел
P_B = (c2 == 1).mean()  # вторая орел
P_AB = ((c1 == 1) & (c2 == 1)).mean()
print(f"P(A)={P_A:.3f}, P(B)={P_B:.3f}, P(AB)={P_AB:.3f} -> независимо: {abs(P_AB - P_A*P_B) < 0.01}")

# === Условная вероятность: вытащим карту, событие 'червы' при условии 'красная' ===
# 52 карты, 26 красных (черви+бубны), 13 червы.
deck = np.array(['HC'] * 13 + ['DC'] * 13 + ['BL'] * 26)
draws = rng.choice(deck, size=N)
red = (draws == 'HC') | (draws == 'DC')
hearts = (draws == 'HC')
P_H_given_R = hearts.sum() / red.sum()
print(f"P(червы | красная) = {P_H_given_R:.4f}  (теор=0.5)")

# === Формула полной вероятности ===
# 3 урны: вероятности выбрать урну p_i; внутри урны вероятность красного шара q_i
p_urn = np.array([0.2, 0.5, 0.3])
q_red = np.array([0.7, 0.1, 0.4])
P_red = p_urn @ q_red
print(f"P(красный) = sum p_i q_i = {P_red:.3f}")

# === Байес: P(урна_2 | красный) ===
P_urn2_given_red = q_red[1] * p_urn[1] / P_red
print(f"P(урна_2 | красный) = {P_urn2_given_red:.4f}")

# === Несовместные != независимые ===
# A = "выпал 1", B = "выпал 2" — несовместны, но НЕ независимы (P(AB)=0 != P(A)P(B))
die = rng.integers(1, 7, N)
pA = (die == 1).mean(); pB = (die == 2).mean(); pAB = ((die == 1) & (die == 2)).mean()
print(f"A=1, B=2: P(AB)={pAB:.4f}, P(A)P(B)={pA*pB:.4f} -> несовместны, НЕ независимы")
