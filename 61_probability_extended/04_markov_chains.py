"""Раздел 61 — Вероятность.

Файл 4: Цепи Маркова (дискретные, конечные).

Концепция: Матрица переходов.
P_{ij} = P(X_{t+1}=j | X_t=i). Строки — распределения, sum_j P_{ij}=1.
Свойство Маркова: будущее зависит только от настоящего.

Концепция: n-шаговая переходная матрица.
P^{(n)} = P^n. (P^n)_{ij} = P(X_n=j | X_0=i). Степень матрицы.

Концепция: Стационарное распределение.
pi такое что pi^T P = pi^T (левый собств. вектор P со значением 1), pi>=0, sum=1.
Если цепь эргодична — pi единственно и lim P^n = 1 pi^T.

Концепция: Эргодичность.
Цепь эргодична, если неразложима (можно достичь любое состояние из любого)
и апериодична (НОД длин циклов = 1). Тогда распределение сходится к pi независимо от старта.
"""
import numpy as np

# === 3-состояния, эргодическая ===
P = np.array([[0.5, 0.4, 0.1],
              [0.2, 0.6, 0.2],
              [0.1, 0.3, 0.6]])

# === n-шаговая матрица ===
P2 = P @ P
P10 = np.linalg.matrix_power(P, 10)
print(f"P^2 строка 0: {P2[0].round(3)}")
print(f"P^10 строка 0: {P10[0].round(4)}")

# === Стационарное pi через левый собств. вектор ===
w, V = np.linalg.eig(P.T)
idx = np.argmin(np.abs(w - 1.0))
pi = np.real(V[:, idx])
pi = pi / pi.sum()
print(f"Стационарное pi = {pi.round(4)}")

# Проверка: pi P = pi
print(f"pi P = {(pi @ P).round(4)}  (должно быть == pi)")

# === Эргодичность: сходимость с разных стартов ===
for start in [0, 1, 2]:
    v = np.zeros(3); v[start] = 1
    v = v @ np.linalg.matrix_power(P, 50)
    print(f"Старт {start} -> через 50 шагов: {v.round(4)}")

# === Эмпирическая проверка стационарности симуляцией ===
rng = np.random.default_rng(0)
state = 0; counts = np.zeros(3)
for _ in range(50_000):
    state = rng.choice(3, p=P[state])
    counts[state] += 1
print(f"Эмп. частоты: {(counts/counts.sum()).round(4)}, теор. pi: {pi.round(4)}")
