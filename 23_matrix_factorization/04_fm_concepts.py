"""Раздел 23 — Матричные разложения. Файл 4: Factorization Machines (концепты).

Концепция 666: Factorization Machines (FM) — формула.
y_hat(x) = w0 + sum_i w_i*x_i + sum_{i<j} <v_i, v_j> * x_i * x_j,
где v_i ∈ R^k — латентный вектор признака i. Это линейная модель плюс
парные взаимодействия, факторизованные через малую размерность.

Концепция 667: Почему FM хороши для разреженных данных.
В обычном poly2 у каждой пары (i,j) свой параметр w_ij — миллиарды коэффициентов
для разреженных данных. В FM пары делят параметры через v_i, v_j —
обобщение даже когда конкретная пара (i,j) не встречалась в обучении.

Концепция 668: Эффективное вычисление парного слагаемого.
sum_{i<j} <v_i,v_j>*x_i*x_j = 0.5 * sum_f [ (sum_i v_{i,f}*x_i)^2
                                            - sum_i v_{i,f}^2 * x_i^2 ].
Линейная сложность по числу ненулевых признаков и k.
"""
import numpy as np

rng = np.random.default_rng(0)

# === 666-668: один forward pass FM на маленьком примере ===
# 4 признака, k=2 латентных измерения
k = 2
w0 = 0.5
w = np.array([0.1, -0.2, 0.05, 0.3])
V = rng.normal(scale=0.1, size=(4, k))  # v_i — строки V

x = np.array([1.0, 0.0, 2.0, 1.0])  # разреженный вектор (один ноль)
print(f"666 x={x.tolist()}")

# линейная часть
linear = w0 + w @ x

# === 668: эффективное парное слагаемое ===
xv = V * x[:, None]              # shape (4, k)
sum_sq = (xv.sum(axis=0)) ** 2   # (sum_i v_{i,f}*x_i)^2
sq_sum = (xv ** 2).sum(axis=0)   # sum_i v_{i,f}^2 * x_i^2
pair_fast = 0.5 * (sum_sq - sq_sum).sum()

# Проверка прямой суммой
pair_naive = 0.0
for i in range(4):
    for j in range(i + 1, 4):
        pair_naive += (V[i] @ V[j]) * x[i] * x[j]

print(f"667 парное слагаемое: эфф. формула={pair_fast:.4f}, "
      f"наивно={pair_naive:.4f}")
y_hat = linear + pair_fast
print(f"668 y_hat = w0 + lin + pair = {linear:.3f} + {pair_fast:.3f} "
      f"= {y_hat:.3f}")

# Иллюстрация: пара (1, j) даёт ноль, потому что x_1=0 — FM это сам учитывает
print("667 Если x_1=0, все взаимодействия с признаком 1 обнуляются автоматически.")
