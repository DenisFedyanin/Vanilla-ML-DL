"""Концепция 115: Теорема Байеса.

P(H|E) = P(E|H) * P(H) / P(E).
Классический пример: 1% людей больны болезнью, тест положителен у 99% больных
и у 5% здоровых. У случайного человека тест положителен. Какова вероятность,
что он действительно болен?
"""
P_H = 0.01            # вероятность быть больным
P_E_given_H = 0.99    # тест положителен, если болен
P_E_given_notH = 0.05 # ложно-положительный

P_E = P_E_given_H * P_H + P_E_given_notH * (1 - P_H)
P_H_given_E = P_E_given_H * P_H / P_E
print(f"P(болен | тест+) = {P_H_given_E:.3f}")
print("Интуитивно люди думают ~99%, но на самом деле ~16% - из-за низкой prior.")
