"""Концепция 7: Закон больших чисел через оценку числа Пи методом Монте-Карло.

Бросаем точки в квадрат [-1,1]x[-1,1]. Доля попавших в круг радиуса 1
стремится к pi/4 при большом числе точек.
"""
import numpy as np

rng = np.random.default_rng(0)
for n in [100, 1_000, 100_000, 1_000_000]:
    pts = rng.uniform(-1, 1, size=(n, 2))
    inside = (pts[:, 0] ** 2 + pts[:, 1] ** 2 <= 1).mean()
    print(f"n={n:>8}  оценка Pi = {4 * inside:.5f}")
