"""Концепция 3: Нормы L1, L2, L_inf.

Норма - это "длина" вектора. Разные нормы по-разному штрафуют большие значения.
"""
import numpy as np

v = np.array([3.0, -4.0, 0.0])

l1 = np.sum(np.abs(v))            # сумма модулей
l2 = np.sqrt(np.sum(v ** 2))      # евклидова длина
linf = np.max(np.abs(v))          # максимум по модулю

print(f"v = {v}")
print(f"L1  = {l1}   (используется в Lasso)")
print(f"L2  = {l2}   (используется в Ridge, евклидова норма)")
print(f"Linf= {linf} (равна максимальной координате по модулю)")
