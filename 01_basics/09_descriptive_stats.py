"""Концепция 9: Описательная статистика.

Среднее, медиана, дисперсия, стандартное отклонение.
"""
import numpy as np

x = np.array([1, 2, 2, 3, 4, 100])  # 100 - выброс

print("Среднее (mean):     ", x.mean(), "  - чувствительно к выбросам")
print("Медиана:            ", np.median(x), "      - устойчива к выбросам")
print("Дисперсия (var):    ", x.var())
print("Std (sqrt дисп.):   ", x.std())
print("Минимум / максимум: ", x.min(), x.max())
print("Перцентили 25/75:   ", np.percentile(x, [25, 75]))
