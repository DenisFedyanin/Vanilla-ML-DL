"""Раздел 56 — Оптимизация (расширение).

Файл 1: Выпуклость.

Концепция: Выпуклое множество.
Множество C выпукло, если для любых x, y из C и t in [0,1]
точка t*x + (1-t)*y тоже в C. Пример: шар, полупространство.

Концепция: Выпуклая функция.
f выпукла, если f(t*x + (1-t)*y) <= t*f(x) + (1-t)*f(y).
Геометрически: график лежит ниже хорды. Любая локальная точка минимума глобальна.

Концепция: Проверка выпуклости вдоль прямой (1D-сужение).
f выпукла <=> g(t) = f(x + t*d) выпукла как 1D-функция при любых x, d.
Удобно для численной проверки на конкретных точках.

Концепция: Сильная выпуклость.
f m-сильно выпукла, если f(y) >= f(x) + grad(x)^T (y-x) + (m/2)||y-x||^2.
Дает линейную скорость сходимости GD. Эквивалент: f - (m/2)||x||^2 выпукла.

Концепция: Неравенство Йенсена.
Для выпуклой f и весов p_i >= 0, sum p_i = 1:
f( sum p_i x_i ) <= sum p_i f(x_i). Это и есть определение, обобщенное на n точек.
"""
import numpy as np

rng = np.random.default_rng(0)

# === Выпуклое множество: пересечение полупространств ===
# C = { x : x>=0, x<=1, x_1+x_2<=1 } — симплекс, выпукл.
x, y = np.array([0.2, 0.3]), np.array([0.5, 0.4])
t = 0.3
z = t * x + (1 - t) * y
in_C = (z >= 0).all() and (z <= 1).all() and z.sum() <= 1
print("Выпуклое множество: t*x+(1-t)*y in C =", in_C)

# === Выпуклая функция: проверка по хорде ===
f = lambda v: (v ** 2).sum()  # f(x) = ||x||^2 выпукла
lhs = f(t * x + (1 - t) * y)
rhs = t * f(x) + (1 - t) * f(y)
print(f"Хорда: f(tx+(1-t)y)={lhs:.4f} <= t f(x)+(1-t) f(y)={rhs:.4f} -> {lhs <= rhs}")

# === Сужение вдоль прямой ===
# f(x)=||x||^2 -> g(t)=||x+t*d||^2 = квадратичная по t, всегда выпукла.
d = np.array([1.0, -1.0])
ts = np.linspace(-1, 1, 5)
g = np.array([f(x + s * d) for s in ts])
# вторая разность >= 0 -> признак выпуклости 1D
second = g[2:] - 2 * g[1:-1] + g[:-2]
print("1D-сужение: вторая разность", second, "(все >=0)")

# === Сильная выпуклость f(x)=0.5*x^T A x, A=I -> m=1 ===
A = np.eye(2)
grad_x = A @ x
m = 1.0
ineq = f(y) - (f(x) + grad_x @ (y - x) + (m / 2) * ((y - x) ** 2).sum())
print(f"Сильная выпуклость (m=1): остаток >=0 -> {ineq:.4f}")

# === Неравенство Йенсена для f(x)=x^2 на 4 точках ===
pts = rng.normal(size=4)
w = rng.uniform(size=4); w /= w.sum()
lhs = (w @ pts) ** 2
rhs = w @ (pts ** 2)
print(f"Йенсен: f(E[X])={lhs:.4f} <= E[f(X)]={rhs:.4f}")
