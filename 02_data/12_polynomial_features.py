"""Концепция 24: Полиномиальные признаки.

Из одной фичи x делаем [x, x^2, x^3]. Это позволяет линейной модели
ловить нелинейные зависимости.
"""
import numpy as np

x = np.array([[2.0], [3.0], [4.0]])

degree = 3
X_poly = np.hstack([x ** d for d in range(1, degree + 1)])

print("Исходное x:\n", x)
print("Полиномиальные признаки (степени 1..3):\n", X_poly)
